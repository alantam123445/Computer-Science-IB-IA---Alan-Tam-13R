class CityGrid: #Object representing the city grid
    def __init__(self, width, height, grid):
        self.width = width 
        self.height = height
        self.grid = grid 
        self.bonus = 0 # 2D list representing the city grid
    def grid_render(self): #Prints the grid in a readable format
        for row in self.grid:
            print(row)
    def is_empty(self, x, y): #Checks if a specific cell in the grid is empty or occupied
        if self.grid[y][x] == '.': #Checks for an empty cell at a specific coordinate
            return "Empty"
        else:
            return "Occupied"
    def neighbour_list(self, x, y): #Calculates the neighbour districts for residential districts based on neighbouring districts
            nearby = []
            for i in range(-1, 2):
                for j in range(-1, 2):
                    if (i == 0 and j == 0) or (x + i < 0 or x + i >= self.width or y + j < 0 or y + j >= self.height):
                        continue
                    if abs(i) == abs(j):
                        continue
                    neighbour = self.grid[y + j][x + i]
                    if neighbour == 'C':
                        nearby.append('C')
                    elif neighbour == 'I':
                        nearby.append('I')
                    elif neighbour == 'P':
                        nearby.append('P')
            return nearby
    def total_upkeep(self): #Calculates the total upkeep cost of all districts on the grid
        total_upkeep = 0
        for row in self.grid:
            for cell in row:
                if cell == 'R':
                    total_upkeep += 5 #Residential districts have an upkeep cost of 5
                elif cell == 'C':
                    total_upkeep += 25 #Commercial districts have an upkeep cost of 25
                elif cell == 'I':
                    total_upkeep += 40 #Industrial districts have an upkeep cost of 40
                elif cell == 'P':
                    total_upkeep += 10 #Recreational districts have an upkeep cost of 10
        return total_upkeep

    def total_income(self): #Calculates the total income generated by all districts on the grid
        total_income = 0
        for row in self.grid:
            for cell in row:
                if cell == 'C':
                    total_income += 100 #Commercial districts generate an income of 100
                elif cell == 'I':
                    total_income += 300 #Industrial districts generate an income of 300
        return total_income
class GameEngine:
    def __init__(self, budget, turn, total_score):
        self.budget = 1000 #Initial budget for the player
        self.turn = 25 #Number of turns the player has
        self.total_score = 0 #Total score of the player
    def end_turn(self, grid): #Ends the turn and updates the budget and score
        self.turn -= 1
        self.budget -= CityGrid.total_upkeep(grid) #Subtracts the total upkeep cost from the budget at the end of each turn
        self.budget += CityGrid.total_income(grid) #Adds the total income to the budget at the end of each turn
        self.total_score += 10 #Adds 10 to the total score at the end of each turn
    def district_draft(self):#Method that choses 2 of the 4 districts randomly for the player to choose from
        districts = [Residential(), Commercial(), Industrial(), Recreational()]
        return random.sample(districts, 2) #Randomly selects 2 districts from the list of 4
    
