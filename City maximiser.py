class District:
    def __init__(self, name, symbol, cost, upkeep, base_score): #Base attributes of the district
        self.name = name #Name of the district eg. residential, commericial
        self.symbol = symbol #Letter symbol representing the district
        self.cost = cost #Cost of placing the district onto the map
        self.upkeep = upkeep #cost of maintaining (residential and recreational only)
        self.base_score = base_score #Score that it would provide to the total
    def get_details(self):  #Prints detail and attributes of the district
        return f"District Name: {self.name}, Symbol: {self.symbol}, Cost: {self.cost}, Upkeep: {self.upkeep}, Base Score: {self.base_score}"

class Residential(District): #Residential subclass
    def __init__(self):
        super().__init__("Residential", "R", 100, 5, 10) #inherits attributes of the district template
        self.population = 50 #provides a population score which contributes to the total, also is needed for placing other stuff
    def get_details(self):
        return f"{super().get_details()}"
    def calculate_bonus(self, nearby): #Calculates the bonus score for residential districts based on neighbouring districts
        bonus = 0
        for district in nearby:
            if district == 'P':
                bonus += 10 #Commercial districts provide a bonus of 10
            elif district == 'I':
                bonus -= 10 #Industrial districts provide a penalty of -10
            elif district == 'C':
                bonus += 3 #Commercial districts provide a bonus of 3
        return bonus
class Commercial(District): #Commercial subclass
    def __init__(self):
        super().__init__("Commercial", "C", 200, 25, 5) #inherits attributes of the district template
        self.revenue = 100 #revenue per round
    def get_details(self):
        return f"{super().get_details()}"
      
class Industrial(District): #industrial subclass
    def __init__(self):
        super().__init__("Industrial", "I", 400, 40, 0) #inherits attributes of the district template
        self.revenue = 300 #Revenue per round
    def get_details(self):
        return f"{super().get_details()}"

class Recreational(District): #recreational subclass
    def __init__(self):
        super().__init__("Park", "P", 100, 10, 15) #inherits attributes of the district template
    def get_details(self):
        return f"{super().get_details()}"
    
class CityGrid: #Object representing the city grid
    def __init__(self, width, height, grid):
        self.width = width 
        self.height = height
        self.grid = grid 
        self.bonus = 0 # 2D list representing the city grid
    def grid_render(self): #Prints the grid in a readable format
        for row in self.grid:
            print(row)
    def is_empty(self, x, y): #Checks if a specific cell in the grid is empty or occupied
        if self.grid[y][x] == '.': #Checks for an empty cell at a specific coordinate
            return True
        else:
            return False
    def neighbour_list(self, x, y): #Calculates the neighbour districts for residential districts based on neighbouring districts
            nearby = []
            for i in range(-1, 2):
                for j in range(-1, 2):
                    if (i == 0 and j == 0) or (x + i < 0 or x + i >= self.width or y + j < 0 or y + j >= self.height):
                        continue
                    if abs(i) == abs(j):
                        continue
                    neighbour = self.grid[y + j][x + i]
                    if neighbour == 'C':
                        nearby.append('C')
                    elif neighbour == 'I':
                        nearby.append('I')
                    elif neighbour == 'P':
                        nearby.append('P')
            return nearby
    def total_upkeep(self): #Calculates the total upkeep cost of all districts on the grid
        total_upkeep = 0
        for row in self.grid:
            for cell in row:
                if cell == 'R':
                    total_upkeep += 5 #Residential districts have an upkeep cost of 5
                elif cell == 'C':
                    total_upkeep += 25 #Commercial districts have an upkeep cost of 25
                elif cell == 'I':
                    total_upkeep += 40 #Industrial districts have an upkeep cost of 40
                elif cell == 'P':
                    total_upkeep += 10 #Recreational districts have an upkeep cost of 10
        return total_upkeep

    def total_income(self): #Calculates the total income generated by all districts on the grid
        total_income = 0
        for row in self.grid:
            for cell in row:
                if cell == 'C':
                    total_income += 100 #Commercial districts generate an income of 100
                elif cell == 'I':
                    total_income += 300 #Industrial districts generate an income of 300
        return total_income
class GameEngine:
    def __init__(self, budget, turn, total_score):
        self.budget = 1000 #Initial budget for the player
        self.turn = 25 #Number of turns the player has
        self.total_score = 0 #Total score of the player
    def end_turn(self, grid): #Ends the turn and updates the budget and score
        self.turn -= 1
        self.budget -= CityGrid.total_upkeep(grid) #Subtracts the total upkeep cost from the budget at the end of each turn
        self.budget += CityGrid.total_income(grid) #Adds the total income to the budget at the end of each turn
        self.total_score += 10 #Adds 10 to the total score at the end of each turn
    def district_draft(self):#Method that choses 2 of the 4 districts randomly for the player to choose from
        districts = [Residential(), Commercial(), Industrial(), Recreational()]
        return random.sample(districts, 2) #Randomly selects 2 districts from the list of 4
    
